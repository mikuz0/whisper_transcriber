"""
exceptions.py - Словарь исключений для исправления конкретных ошибок
Без автоматической лемматизации!
"""

import re


class ExceptionDictionary:
    """
    Словарь исключений для исправления конкретных слов
    
    Используется только для явно заданных замен,
    не применяет автоматическую лемматизацию.
    """
    
    # Только конкретные слова, которые точно нужно исправить
    EXCEPTIONS = {
        # Просторечные формы (только явные случаи)
        'пошол': 'пошёл',
        'пришол': 'пришёл',
        'ишол': 'шёл',
        'зашол': 'зашёл',
        'вышол': 'вышел',
        
        # Распространённые ошибки
        'ихний': 'их',
        'евонный': 'его',
        'ейный': 'её',
        
        # Сокращения
        'щас': 'сейчас',
        'ща': 'сейчас',
        'токо': 'только',
        'тока': 'только',
        'че': 'что',
        'чо': 'что',
        
        # Частицы
        'небыло': 'не было',
        'небудет': 'не будет',
        'немогу': 'не могу',
        'незнаю': 'не знаю',
    }
    
    def __init__(self):
        pass
    
    def apply(self, text: str) -> str:
        """
        Применяет словарь исключений к тексту
        
        Args:
            text: исходный текст
            
        Returns:
            текст с исправленными исключениями
        """
        if not text:
            return text
        
        for wrong, correct in self.EXCEPTIONS.items():
            # Заменяем слово целиком, а не часть
            text = re.sub(r'\b' + wrong + r'\b', correct, text)
        
        return text